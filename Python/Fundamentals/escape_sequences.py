# \" - Double Quote - This adds a double quote to the string
# \' - Single Quote - This adds a single quote to the string
# \\ - Backslash - This adds a backslash to the string
# \t - Tab - This creates a tab space
# \n - New Line - This creates a new line

# <*************************************************************>

# This adds a double quote to the string
print("Hi \"Python\"")

# This adds a single quote to the string
print('Hi \'Python\'')

# This adds a backslash to the string
print("This is a backslash: \\")

# This creates a tab space
print("Hello, \tWorld!")

# This creates a new line
print("This is a new line.\nThis is the second line.")
# <*************************************************************>
